// Copies the shared UI text from the web app so both apps say the same thing.
// Run: node scripts/sync-locales.mjs   (the web files stay the source of truth)
import { copyFileSync, writeFileSync } from 'node:fs';
const from = '../web/locales/';
const to = './src/locales/';
for (const f of ['common', 'tasks', 'detail', 'settings', 'errors']) copyFileSync(`${from}${f}.ts`, `${to}${f}.ts`);
writeFileSync(
  `${to}index.ts`,
  `import { common } from './common';\nimport { tasks } from './tasks';\nimport { detail } from './detail';\nimport { settings } from './settings';\nimport { mobile } from './mobile';\n\n/** key -> [English, বাংলা] (generated by scripts/sync-locales.mjs) */\nexport const DICT: Record<string, [string, string]> = { ...common, ...tasks, ...detail, ...settings, ...mobile };\n`,
);
console.log('locales synced');
